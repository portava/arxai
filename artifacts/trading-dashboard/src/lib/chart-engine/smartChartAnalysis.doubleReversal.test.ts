import {afterEach,expect,it,vi} from "vitest";
import * as patterns from "@workspace/domain/chart-patterns";
import {analyzeSmartChart,type SmartChartAnalysisBar} from "./smartChartAnalysis";
const detect=patterns.detectChartPatterns;
afterEach(()=>vi.restoreAllMocks());
const points=[[0,90],[8,96],[12,105],[20,99],[28,105],[30,102],[31,98],[32,97]];
const bars:SmartChartAnalysisBar[]=Array.from({length:33},(_,i)=>{const j=points.findIndex(p=>p[0]!>=i),a=points[Math.max(0,j-1)]!,b=points[j]!,close=j===0?90:a[1]!+(b[1]!-a[1]!)*(i-a[0]!)/(b[0]!-a[0]!);return{time:1700000000+i*300,closeTime:1700000000+(i+1)*300,open:close-.05,high:close+.2,low:close-.2,close,isComplete:true,isFinal:true,isForming:false};});
const input={symbol:"EURUSD",timeframe:"M5",source:"mt5_broker",sourceIdentity:"a".repeat(64),bars,asOfMs:bars.at(-1)!.closeTime*1000,dataState:"current" as const};
it.each(["missing","future confirmation","premature confirmation","unordered anchors","future formation","invalid volatility","missing confirmation","failure before confirmation","missing failure","status disagrees","late false confirmation","false failure","mismatched identity","extra anchor","wrong role","wrong price","wrong level","wrong reference"])("does not render double reversal with %s evidence",kind=>{
 const actual=detect(bars).patterns.find(p=>p.id==="double_top");expect(actual?.doubleReversalLifecycle).toBeDefined();
 vi.spyOn(patterns,"detectChartPatterns").mockImplementation(candles=>{const result=detect(candles);return{...result,patterns:result.patterns.map(raw=>{if(raw.id!=="double_top")return raw;const p=structuredClone(raw),life=p.doubleReversalLifecycle!;
 switch(kind){
 case "missing":delete p.doubleReversalLifecycle;break;
 case "future confirmation":life.confirmedIndex=candles.length;break;
 case "premature confirmation":life.confirmedIndex=life.formationKnownAtIndex;break;
 case "unordered anchors":life.formationIndexes=[28,20,12];break;
 case "future formation":life.formationKnownAtIndex=candles.length;break;
 case "invalid volatility":life.frozenAtr=NaN;break;
 case "missing confirmation":life.confirmedIndex=null;p.status="confirmed";break;
 case "failure before confirmation":life.failedIndex=life.confirmedIndex!;p.status="invalidated";break;
 case "missing failure":p.status="invalidated";life.failedIndex=null;break;
 case "status disagrees":p.status="forming";break;
 case "late false confirmation":life.confirmedIndex=32;break;
 case "false failure":life.failedIndex=32;p.status="invalidated";break;
 case "mismatched identity":life.formationIndexes=[11,20,28];break;
 case "extra anchor":p.keyPoints.push({index:22,price:100,role:"extra"});break;
 case "wrong role":p.keyPoints[0]!.role="second_top";break;
 case "wrong price":p.keyPoints[0]!.price+=1;break;
 case "wrong level":p.levels.confirmation=100;break;
 case "wrong reference":life.referenceLevel=100;break;
 }return p;})};});
 expect(analyzeSmartChart(input).allFindings.some(f=>f.id.startsWith("double_top"))).toBe(false);
});
